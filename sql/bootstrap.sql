-- Run with a role authorized to create a warehouse/database in a Snowflake trial.
-- Small warehouse with fast auto-suspend to control cost.
CREATE WAREHOUSE IF NOT EXISTS WEALTHOPS_WH
 WAREHOUSE_SIZE='XSMALL'
 AUTO_SUSPEND=60
 AUTO_RESUME=TRUE
 INITIALLY_SUSPENDED=TRUE;
CREATE DATABASE IF NOT EXISTS WEALTHOPS_DB;
CREATE SCHEMA IF NOT EXISTS WEALTHOPS_DB.RAW;
CREATE SCHEMA IF NOT EXISTS WEALTHOPS_DB.STAGING;
CREATE SCHEMA IF NOT EXISTS WEALTHOPS_DB.INTERMEDIATE;
CREATE SCHEMA IF NOT EXISTS WEALTHOPS_DB.MARTS;
CREATE SCHEMA IF NOT EXISTS WEALTHOPS_DB.AUDIT;

